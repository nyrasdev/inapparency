#!/usr/bin/env python3
"""Turns the logo into the bitmap the OLED splash screen draws.

Takes either the braille text art or a picture (PNG, ideally already 1-bit
and at most 128x64), scales it to fit the screen and writes
modules/display/src/logo.cpp. The generated file is committed, so normal
builds don't need Python or Pillow.

    python3 tools/make_logo.py assets/protogen-braille.txt
    python3 tools/make_logo.py assets/logo.png --invert

Needs Pillow (pip install pillow).
"""

import argparse
import pathlib
import shutil
import subprocess
import sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "modules" / "display" / "src" / "logo.cpp"
MAX_W, MAX_H = 128, 64

# Braille dot number -> (x, y) inside the 2x4 cell.
DOTS = [(0, 0), (0, 1), (0, 2), (1, 0), (1, 1), (1, 2), (0, 3), (1, 3)]


def from_braille(path):
    lines = path.read_text(encoding="utf-8").rstrip("\n").split("\n")
    width = max(len(line) for line in lines) * 2
    img = Image.new("L", (width, len(lines) * 4), 0)
    px = img.load()
    for row, line in enumerate(lines):
        for col, ch in enumerate(line):
            code = ord(ch) - 0x2800 if 0x2800 <= ord(ch) <= 0x28FF else 0
            for bit, (dx, dy) in enumerate(DOTS):
                if code >> bit & 1:
                    px[col * 2 + dx, row * 4 + dy] = 255
    return img


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("source", type=pathlib.Path, help="braille .txt or an image")
    ap.add_argument("--invert", action="store_true", help="swap lit and dark pixels")
    ap.add_argument("--threshold", type=int, default=128, help="0-255, for scaled images")
    args = ap.parse_args()

    if args.source.suffix.lower() == ".txt":
        img = from_braille(args.source)
    else:
        # Transparent parts count as dark.
        src = Image.open(args.source).convert("RGBA")
        bg = Image.new("RGBA", src.size, (0, 0, 0, 255))
        img = Image.alpha_composite(bg, src).convert("L")

    if args.invert:
        img = img.point(lambda v: 255 - v)

    scale = min(MAX_W / img.width, MAX_H / img.height, 1.0)
    if scale < 1.0:
        size = (max(1, round(img.width * scale)), max(1, round(img.height * scale)))
        img = img.resize(size, Image.LANCZOS)
    img = img.point(lambda v: 255 if v >= args.threshold else 0)

    w, h = img.size
    px = img.load()
    stride = (w + 7) // 8
    data = []
    for y in range(h):
        for bx in range(stride):
            byte = 0
            for bit in range(8):
                x = bx * 8 + bit
                if x < w and px[x, y]:
                    byte |= 0x80 >> bit
            data.append(byte)

    rows = []
    for i in range(0, len(data), 12):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 12]) + ",")

    OUT.write_text(
        f"""// Generated by tools/make_logo.py from {args.source.name}. Don't edit by hand.

#include "inapparency/display/logo.hpp"

#include <array>

namespace inapparency::display {{
namespace {{

constexpr std::array<std::uint8_t, {len(data)}> kData{{{{
{chr(10).join(rows)}
}}}};

}} // namespace

const Bitmap kLogoBitmap{{{w}, {h}, kData.data()}};

}} // namespace inapparency::display
""",
        encoding="utf-8",
    )
    # Match the repo's formatting so CI's format check stays happy.
    for tool in ("clang-format-18", "clang-format"):
        if shutil.which(tool):
            subprocess.run([tool, "-i", str(OUT)], check=False)
            break
    print(f"wrote {OUT.relative_to(ROOT)}: {w}x{h} px, {len(data)} bytes")


if __name__ == "__main__":
    sys.exit(main())
